    for role, difficulties in ALL_TECH_QUESTIONS.items():
        for difficulty, questions in difficulties.items():
            for q in questions:
                docs.append({
                    "role": role,
                    "type": "technical",
                    "difficulty": difficulty,
                    "question": q,
                    "asked_count": 0,
                    "avg_score": 0.0,
                    "total_score_sum": 0.0,
                    "times_scored": 0,
                })
    return docs


